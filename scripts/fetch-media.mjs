// Baixa imagens com licença livre do Wikimedia Commons e registra crédito e licença de cada uma.
// - Capas de período: série "Trek Through Time" do USGS (domínio público), recortada para a área da ilustração.
// - Organismos: imagem principal do artigo da Wikipédia (en) de cada gênero, classificada em
//   fóssil/espécime × reconstrução artística a partir das categorias e da descrição do Commons.
// As imagens NÃO são baixadas: o app usa as miniaturas servidas pelo próprio Commons (upload.wikimedia.org).
// Uso: node scripts/fetch-media.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const today = new Date().toISOString().slice(0, 10);
const UA = { 'User-Agent': 'Geolytha/0.1 (prototipo educativo)' };
const COMMONS = 'https://commons.wikimedia.org/w/api.php?format=json&action=query&';
const strip = (s) => (s ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim();
const ALLOWED = /^(public domain|cc0|cc by(-sa)? [\d.]+( [a-z]+)?|no restrictions)$/i;

const pause = (ms) => new Promise((r) => setTimeout(r, ms));
const getJson = async (url) => {
  await pause(1500);
  for (let i = 0; i < 6; i++) {
    const r = await fetch(url, { headers: UA });
    if (r.ok) return r.json();
    await new Promise((res) => setTimeout(res, 10000 * (i + 1)));
  }
  throw new Error(`falha: ${url}`);
};

async function commonsInfo(file, width) {
  const j = await getJson(`${COMMONS}prop=imageinfo|categories&cllimit=max&iiprop=url|size|extmetadata${width ? `&iiurlwidth=${width}` : ''}&titles=${encodeURIComponent('File:' + file)}`);
  const p = Object.values(j.query.pages)[0];
  const ii = p.imageinfo?.[0];
  if (!ii) return null;
  const e = ii.extmetadata ?? {};
  return {
    url: ii.url, thumb: ii.thumburl ?? ii.url, width: ii.width, height: ii.height,
    pageUrl: ii.descriptionurl,
    license: strip(e.LicenseShortName?.value), licenseUrl: e.LicenseUrl?.value ?? null,
    artist: strip(e.Artist?.value), credit: strip(e.Credit?.value), description: strip(e.ImageDescription?.value).slice(0, 300),
    categories: (p.categories ?? []).map((c) => c.title.replace('Category:', '')),
  };
}

const media = [];

// ---------- Capas de período (USGS Trek Through Time) ----------
const COVERS = {
  cambrian: 'TTT Cambrian (2).png', ordovician: 'TTT Ordovician (2).png', silurian: 'TTT Silurian (2).png',
  devonian: 'TTT Devonian (2).png', carboniferous: 'TTT Carboniferous (3).png', permian: 'TTT Permian (2).png',
  triassic: 'TTT Triassic (2).png', jurassic: 'TTT Jurassic (2).png', cretaceous: 'TTT Cretaceous (2).png',
  paleocene: 'TTT Paleocene (2).png', eocene: 'TTT Eocene (2).png', oligocene: 'TTT Oligocene (2).png',
  miocene: 'TTT Miocene (2).png', pliocene: 'TTT Pliocene (2).png', pleistocene: 'TTT Pleistocene (2).png',
};
// área da ilustração dentro do pôster (frações), excluindo título, logotipo e minimapa
const CROP = { left: 0.19, top: 0.225, width: 0.78, height: 0.53 };
for (const [intervalId, file] of Object.entries(COVERS)) {
  process.stdout.write(`capa ${intervalId}… `);
  const info = await commonsInfo(file, 1280);
  if (!info || !ALLOWED.test(info.license)) { console.log(`ignorada (licença: ${info?.license})`); continue; }
  media.push({
    id: `cover-${intervalId}`, intervalId, url: info.thumb, crop: CROP, kind: 'artistic_reconstruction',
    caption: info.description || `Reconstrução artística do ${intervalId}`, credit: info.artist || info.credit, source: info.credit,
    license: info.license, licenseUrl: info.licenseUrl, sourceUrl: info.pageUrl,
    modified: 'Exibido recortado na área da ilustração (sem título, logotipo e minimapa).',
    aiGenerated: false, fetchedAt: today,
  });
  console.log(info.license);
}

// ---------- Organismos (imagem principal da Wikipédia) ----------
const taxa = JSON.parse(readFileSync(join(root, 'src/data/taxa/taxa.json'), 'utf8')).taxa;
const ART = /restoration|reconstruct|paleoart|life[ -]?restor|artist|illustration|drawing|render/i;
const FOSSIL = /fossil|skelet|skull|specimen|holotype|cast\b|mount|museum|bone|teeth|tooth|jaw|cranium/i;
const AI = /AI-generated|artificial intelligence|generated by/i;
for (const t of taxa) {
  process.stdout.write(`${t.name}… `);
  const j = await getJson(`https://en.wikipedia.org/w/api.php?format=json&action=query&prop=pageimages&piprop=name&redirects=1&titles=${encodeURIComponent(t.name)}`);
  const file = Object.values(j.query.pages)[0]?.pageimage;
  if (!file) { console.log('sem imagem'); continue; }
  const info = await commonsInfo(file, 640);
  if (!info) { console.log('arquivo não está no Commons'); continue; }
  const cats = info.categories.join(' | ');
  if (AI.test(cats) || AI.test(info.description)) { console.log('ignorada (IA)'); continue; }
  if (!ALLOWED.test(info.license)) { console.log(`ignorada (licença: ${info.license})`); continue; }
  const text = `${file} ${info.description} ${cats}`;
  const OVERRIDE = { homo: 'unclassified', shonisaurus: 'unclassified', pakicetus: 'unclassified', staurikosaurus: 'unclassified', megaloceros: 'unclassified' }; // revisão manual
  const kind = OVERRIDE[t.id] ?? (ART.test(text) && !/skelet|specimen|holotype/i.test(file) ? 'artistic_reconstruction' : FOSSIL.test(text) ? 'fossil_photo' : 'unclassified');
  media.push({
    id: `taxon-${t.id}`, taxonId: t.id, url: info.thumb, kind,
    caption: info.description || file.replace(/\.\w+$/, ''), credit: info.artist || info.credit, source: info.credit,
    license: info.license, licenseUrl: info.licenseUrl, sourceUrl: info.pageUrl,
    modified: 'Exibido reduzido e recortado no cartão.',
    aiGenerated: false, fetchedAt: today, classifiedBy: 'heurística (categorias e descrição do Commons) — revisar',
  });
  console.log(`${kind} · ${info.license}`);
}

writeFileSync(join(root, 'src/data/media/media.json'), JSON.stringify({ fetchedAt: today, source: 'Wikimedia Commons', media }, null, 1) + '\n');
console.log(`✓ ${media.length} imagens.`);
